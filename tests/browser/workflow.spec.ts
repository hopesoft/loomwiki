import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';

test('source to reviewed knowledge, conflicting update, history, retry, and responsive layout', async ({ page }, testInfo) => {
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 async function screenshot(name:string){
  const output=process.env.LOOMWIKI_CAPTURE_DEMO==='1'?path.resolve('docs/images',name+'.png'):testInfo.outputPath(name+'.png');
  await mkdir(path.dirname(output),{recursive:true});await page.screenshot({path:output,fullPage:true});
 }
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Knowledge worth keeping.'})).toBeVisible();
 await page.getByRole('button',{name:'Go to Inbox'}).click();
 await page.locator('input[type=file]').setInputFiles('fixtures/retention-policy.md');
 await expect(page.getByRole('heading',{name:'retention-policy.md',exact:true})).toBeVisible();
 await expect(page.getByText('test://local-fixture',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Send to AI & prepare review'}).click();
 await expect(page.getByRole('heading',{name:'Review what changes.'})).toBeVisible();
 await expect(page.getByText('A new page. Nothing is being replaced.')).toBeVisible();
 await page.getByText('1 source reference',{exact:true}).click();
 await page.getByRole('button',{name:'Inspect original'}).click();
 await expect(page.getByRole('region',{name:'Original source'}).locator('pre')).toContainText('retains audit logs for 30 days');
 await page.getByRole('button',{name:'Close original'}).click();
 await expect(page.getByRole('region',{name:'Original source'})).toHaveCount(0);
 await page.getByRole('button',{name:'Accept update',exact:true}).click();
 await expect(page.getByText('Accepted into Knowledge.',{exact:false})).toBeVisible();
 await page.getByRole('navigation',{name:'Workspace'}).getByRole('button',{name:/Knowledge/}).click();
 await page.getByRole('button',{name:/Birch retention policy/}).click();
 await expect(page.getByText('ACCEPTED · REVISION 1')).toBeVisible();
 await page.getByRole('navigation',{name:'Workspace'}).getByRole('button',{name:/Inbox/}).click();
 await page.locator('input[type=file]').setInputFiles('fixtures/revised/retention-policy.md');
 await page.getByRole('button',{name:'Send to AI & prepare review'}).click();
 await expect(page.getByRole('heading',{name:'Unresolved perspectives'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Accept update',exact:true})).toBeDisabled();
 await screenshot('review');
 await page.getByLabel('Your decision on the disagreement (required)').fill('Retain both perspectives until the policy owner clarifies the discrepancy.');
 await page.getByRole('button',{name:'Accept update',exact:true}).click();
 await expect(page.getByText('Accepted into Knowledge.',{exact:false})).toBeVisible();
 await page.reload();
 await page.getByRole('button',{name:/Birch retention policy/}).click();
 await expect(page.getByText('ACCEPTED · REVISION 2')).toBeVisible();
 await page.getByRole('button',{name:'View revision history'}).click();
 await page.locator('summary').filter({hasText:'Revision 1 ·'}).click();
 await expect(page.locator('.history > details').filter({has:page.locator('summary').filter({hasText:'Revision 1 ·'})}).getByText('Project Birch retains audit logs for 30 days.',{exact:true})).toBeVisible();
 await screenshot('knowledge');
 await page.getByRole('navigation',{name:'Workspace'}).getByRole('button',{name:/Inbox/}).click();
 await page.getByRole('button',{name:'Paste text'}).click();
 await page.getByLabel('Source filename').fill('retry.md');
 await page.getByLabel('Source text').fill('Additional synthetic notes for retry and rejection.');
 await page.getByRole('button',{name:'Save source locally'}).click();
 await page.getByRole('button',{name:'Send to AI & prepare review'}).click();
 await expect(page.getByRole('alert')).toContainText('Synthetic provider failure');
 await page.getByRole('button',{name:'Send to AI & prepare review'}).click();
 await page.getByRole('button',{name:'Reject suggestion',exact:true}).click();
 await expect(page.getByText('Rejected. Knowledge was not changed.',{exact:false})).toBeVisible();
 const workspace=await (await page.request.get('/api/workspace')).json();
 expect(workspace.pages).toHaveLength(1);expect(workspace.pages[0].revision).toBe(2);
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('navigation',{name:'Workspace'}).getByRole('button',{name:/Knowledge/}).click();
 await page.getByRole('button',{name:/Birch retention policy/}).click();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await expect(page.getByRole('navigation',{name:'Workspace'})).toBeVisible();
 await screenshot('mobile');
 expect(errors).toEqual([]);
});
